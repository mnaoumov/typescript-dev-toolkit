/**
 * Removes everything an earlier build left: `dist/`, the generated `index.ts` barrels, the `.d.ts` files `tsc` wrote
 * beside the sources (hand-authored ones under `@types` stay), and the per-subpath `package.json` stubs.
 *
 * @returns A {@link Promise} that resolves when everything has been removed.
 */
export async function buildCleanLibrary(): Promise<void> {
  await buildClean();
  for (const file of await readdirPosix(RepoPaths.Src, { recursive: true })) {
    if (basename(file) === RepoPaths.IndexTs as string) {
      await rm(join(RepoPaths.Src, file));
    }

    if (file.endsWith(RepoPaths.DtsExtension) && !file.split('/').includes(RepoPaths.Types)) {
      await rm(join(RepoPaths.Src, file));
    }
  }

  for (const file of await readdirPosix(RepoPaths.CurrentFolder, { recursive: true })) {
    if ((basename(file) !== RepoPaths.PackageJson as string) || (file === RepoPaths.PackageJson as string) || file.startsWith(RepoPaths.NodeModules)) {
      continue;
    }

    await rm(file);
  }
}

/**
 * Builds every source module, unbundled, into `dist/lib/cjs` (`.cjs`) and `dist/lib/esm` (`.mjs`).
 *
 * The output folders must already exist; {@link buildLibraryTypes} creates them.
 *
 * @param options - The build options.
 * @returns A {@link Promise} that resolves when both formats have been built.
 */
export async function buildLibrary(options: BuildLibraryOptions = {}): Promise<void> {
  const { preprocessPluginFactory = (isEsm: boolean): Plugin => preprocessPlugin({ isEsm }) } = options;
  const libFiles = await getLibFiles();
  await buildLibraryFormat({ format: 'cjs', libFiles, preprocessPluginFactory });
  await buildLibraryFormat({ format: 'esm', libFiles, preprocessPluginFactory });
}

/**
 * Emits the declarations with `tsc --project ./tsconfig.types.json`, then copies each one into `dist/lib` twice: as a
 * `.d.cts` whose relative imports name `.cjs` files and whose bare type imports carry `resolution-mode: import`, and
 * as a `.d.mts` whose relative imports name `.mjs` files.
 *
 * The library's root declaration (`library.ts` where the package has one, otherwise the generated `index.ts`) carries
 * every `lib` and `types` reference the package needs. Every other declaration references a `library-references`
 * declaration beside it by path, never the root: the root barrel re-exports every module, so referencing it made each
 * subpath load the whole package, and a consumer type-checking with `skipLibCheck: false` then needed every optional
 * peer installed.
 *
 * `library-references` carries only the libs that describe the language (`es2022`, `esnext.disposable`), which no
 * consumer conflicts with. The ones that describe a host (`dom`, `dom.iterable`, `webworker`) and `types="node"` go
 * only into the declarations that name one of their globals, found by resolving every name in the emitted
 * declarations with the type checker. Otherwise a browser consumer of a pure subpath got all of `@types/node`, and its
 * `setTimeout` returned `NodeJS.Timeout`.
 *
 * @returns A {@link Promise} that resolves when the declarations have been written.
 * @throws If a source module is named `library-references`, which would collide with the generated declaration.
 */
export async function buildLibraryTypes(): Promise<void> {
  if (existsSync(join(RepoPaths.Src, `${LIBRARY_REFERENCES_FILE_NAME}${RepoPaths.TsExtension}`))) {
    throw new Error(`src/${LIBRARY_REFERENCES_FILE_NAME}${RepoPaths.TsExtension} collides with the generated declaration of the same name.`);
  }

  await execFromRoot([...resolveToolCommand({ tool: 'tsc' }), '--project', './tsconfig.types.json']);

  const libraryFileName = existsSync(join(RepoPaths.Src, 'library.ts')) ? 'library' : 'index';
  const allLibs = await collectAllLibs();
  const allTypes = collectAllTypes();
  const directives = buildAllReferenceLibDirectives(allLibs) + buildAllReferenceTypesDirectives(allTypes);
  // Only the libs no consumer conflicts with. The environment globals go to the declarations that use them.
  const sharedDirectives = buildAllReferenceLibDirectives(allLibs.filter((lib) => !isEnvironmentLib(lib)));

  await mkdir(join(RepoPaths.DistLib, RepoPaths.Cjs), { recursive: true });
  await mkdir(join(RepoPaths.DistLib, RepoPaths.Esm), { recursive: true });
  await writeFile(join(RepoPaths.DistLib, RepoPaths.Cjs, LIBRARY_REFERENCES_FILE_NAME + RepoPaths.DctsExtension), sharedDirectives);
  await writeFile(join(RepoPaths.DistLib, RepoPaths.Esm, LIBRARY_REFERENCES_FILE_NAME + RepoPaths.DmtsExtension), sharedDirectives);

  const srcFiles = await readdirPosix(RepoPaths.Src, { recursive: true });
  const declarationFiles = srcFiles.filter((file) => file.endsWith(RepoPaths.DtsExtension) && !file.startsWith(RepoPaths.TestHelpers));
  const environmentDirectives = collectEnvironmentDirectives({ availableTypes: allTypes, declarationFiles });

  for (const file of declarationFiles) {
    const folder = dirname(file);
    const name = basename(file, RepoPaths.DtsExtension);
    const content = await readFile(join(RepoPaths.Src, file), 'utf-8');

    const ctsPath = join(RepoPaths.DistLib, RepoPaths.Cjs, folder, name + RepoPaths.DctsExtension);
    const mtsPath = join(RepoPaths.DistLib, RepoPaths.Esm, folder, name + RepoPaths.DmtsExtension);

    await mkdir(dirname(ctsPath), { recursive: true });
    await mkdir(dirname(mtsPath), { recursive: true });

    let ctsContent = toCtsContent(content);
    let mtsContent = toMtsContent(content);

    if (name === libraryFileName && folder === '.') {
      ctsContent = directives + ctsContent;
      mtsContent = directives + mtsContent;
    } else {
      const fileDirectives = environmentDirectives.get(file) ?? '';
      ctsContent = buildReferencePathDirective({ declarationFilePath: ctsPath, extension: RepoPaths.DctsExtension, moduleDirectory: RepoPaths.Cjs })
        + fileDirectives + ctsContent;
      mtsContent = buildReferencePathDirective({ declarationFilePath: mtsPath, extension: RepoPaths.DmtsExtension, moduleDirectory: RepoPaths.Esm })
        + fileDirectives + mtsContent;
    }

    await writeFile(ctsPath, ctsContent);
    await writeFile(mtsPath, mtsContent);
  }
}

/**
 * Regenerates the `exports` map of the package's `package.json` from its source folders, and writes a `package.json`
 * stub per subpath for resolvers that do not read `exports`.
 *
 * @param options - The {@link GenerateLibraryExportsOptions}.
 * @returns A {@link Promise} that resolves when the map is current.
 * @throws If the map changed, so the change gets reviewed and committed rather than shipped unseen.
 */
export async function generateLibraryExports(options: GenerateLibraryExportsOptions = {}): Promise<void> {
  const { additionalExports = {}, sourceCondition } = options;
  const srcFolders: string[] = [RepoPaths.Src];

  for (const dirent of await readdirPosix(RepoPaths.Src, { recursive: true, withFileTypes: true })) {
    if (!dirent.isDirectory()) {
      continue;
    }

    const path = join(dirent.parentPath, dirent.name);

    if (path.includes(RepoPaths.Styles) || path.includes(RepoPaths.TestHelpers)) {
      continue;
    }

    srcFolders.push(path);
  }

  srcFolders.sort();

  let isChanged = false;

  await editPackageJson(async (packageJson) => {
    const oldExports = packageJson.exports;
    const exportConditions: PackageJson.ExportConditions = {};
    packageJson.exports = exportConditions;
    for (const srcFolder of srcFolders) {
      await setExport({ exportConditions, isWildcard: false, sourceCondition, srcFolder });
      await setExport({ exportConditions, isWildcard: true, sourceCondition, srcFolder });
    }

    for (const [subpath, entry] of Object.entries(additionalExports)) {
      if (exportConditions[subpath] !== undefined) {
        throw new Error(`The additional export '${subpath}' collides with an entry generated from a source folder.`);
      }

      exportConditions[subpath] = entry;
    }

    isChanged = !isDeepEqual(oldExports, packageJson.exports);
  });

  // eslint-disable-next-line @typescript-eslint/no-unnecessary-condition -- It changed in the `editPackageJson`, ESLint mistakenly does not recognize it.
  if (isChanged) {
    throw new Error('Package exports have changed. Please review the changes and commit them.');
  }
}

/**
 * Generates an `index.ts` barrel in every source folder that has something to export, re-exporting each module and
 * each sub-barrel under its own name.
 *
 * @param options - The options.
 * @returns A {@link Promise} that resolves when the barrels have been written.
 */
export async function generateLibraryIndex(options: GenerateLibraryIndexOptions = {}): Promise<void> {
  const excludedPaths = new Set((options.excludeFromIndex ?? []).map((path) => join(path.replaceAll('\\', '/')).replace(/\/$/, '')));
  const unmatchedPaths = new Set(excludedPaths);
  await generateIndex({ excludedPaths, folder: RepoPaths.Src, unmatchedPaths });

  if (unmatchedPaths.size > 0) {
    throw new Error(`excludeFromIndex names no module the barrels would export: ${[...unmatchedPaths].join(', ')}.`);
  }
}

/**
 * Runs each named npm script the package defines, in order, skipping the ones it does not define.
 *
 * @param steps - The npm script names.
 * @returns A {@link Promise} that resolves when every step has run.
 */
export async function runBuildSteps(steps: readonly string[] = LIBRARY_BUILD_STEPS): Promise<void> {
  for (const step of steps) {
    await npmRunOptional(step);
  }
}

/**
 * Adds what a consumer needs loaded for one symbol a declaration names. A symbol any ES lib declares needs nothing,
 * because no consumer conflicts with those libs. Otherwise each environment lib that declares it adds itself, and
 * failing that `@types/node` adds `node`. A symbol declared in the package's own files adds nothing: the declaration
 * that holds it carries its own directives.
 *
 * @param params - The symbol, the program it was resolved in, and the sets to add to.
 */
function addEnvironmentGlobals(params: AddEnvironmentGlobalsParams): void {
  const { libs, program, symbol: $symbol, types } = params;
  const environmentLibs: string[] = [];
  let isNode = false;

  for (const declaration of $symbol.declarations ?? []) {
    const sourceFile = declaration.getSourceFile();
    if (program.isSourceFileDefaultLibrary(sourceFile)) {
      const lib = toLibName(sourceFile.fileName);
      if (!isEnvironmentLib(lib)) {
        return;
      }
      environmentLibs.push(lib);
    } else if (sourceFile.fileName.includes(NODE_TYPES_PATH_SEGMENT)) {
      isNode = true;
    }
  }

  if (environmentLibs.length > 0) {
    for (const lib of environmentLibs) {
      libs.add(lib);
    }
  } else if (isNode) {
    types.add('node');
  }
}

function buildAllReferenceLibDirectives(libs: string[]): string {
  return `${
    libs
      .map((lib) => `/// ${REFERENCE_LIB_DIRECTIVE}"${lib}" />`)
      .join('\n')
  }\n`;
}

function buildAllReferenceTypesDirectives(types: string[]): string {
  return types.length === 0
    ? ''
    : `${
      types
        .map((type) => `/// <reference types="${type}" />`)
        .join('\n')
    }\n`;
}

async function buildLibraryFormat(params: BuildLibraryFormatParams): Promise<void> {
  const { format, libFiles, preprocessPluginFactory } = params;
  const extension = format === 'cjs' ? RepoPaths.CjsExtension : RepoPaths.MjsExtension;
  const buildOptions: BuildOptions = {
    // Explicit, because esbuild otherwise takes the folder its service process started in.
    // eslint-disable-next-line unicorn/name-replacements -- esbuild's own option name.
    absWorkingDir: process.cwd(),
    banner: {
      js: LIBRARY_BANNER
    },
    bundle: false,
    entryPoints: libFiles,
    format,
    logLevel: 'info',
    outdir: join(RepoPaths.DistLib, format),
    platform: 'node',
    plugins: [
      preprocessPluginFactory(format === 'esm'),
      fixEsmPlugin(),
      changeExtensionPlugin(extension)
    ],
    sourcemap: 'inline',
    target: 'ES2022',
    treeShaking: true,
    write: false
  };

  const buildContext = await context(buildOptions);
  try {
    await buildContext.rebuild();
  } finally {
    await buildContext.dispose();
  }
}

function buildReferencePathDirective(params: BuildReferencePathDirectiveParams): string {
  const { declarationFilePath, extension, moduleDirectory } = params;
  const libraryFilePath = join(RepoPaths.DistLib, moduleDirectory, LIBRARY_REFERENCES_FILE_NAME + extension);
  let relativePath = relativeNative(dirname(declarationFilePath), libraryFilePath).replaceAll('\\', '/');
  if (!relativePath.startsWith('.')) {
    relativePath = `./${relativePath}`;
  }
  return `/// <reference path="${relativePath}" />\n`;
}

async function collectAllLibs(): Promise<string[]> {
  // The RESOLVED options, because a package's `tsconfig.json` inherits `lib` from the shared base. The resolved
  // names are file names (`lib.dom.iterable.d.ts`), so they are mapped back onto the names a directive takes.
  const { options } = parseTsConfig(RepoPaths.TsConfigJson);
  const libs = new Set((options.lib ?? []).map((lib) => toLibName(lib)));

  for (const file of await readdirPosix(RepoPaths.Src, { recursive: true })) {
    if (!file.endsWith('.ts')) {
      continue;
    }

    const sourceContent = readFileSync(join(RepoPaths.Src, file), 'utf-8');
    // The regular expression always captures its one group, so no fallback for a missing one is needed.
    for (const [, lib] of sourceContent.matchAll(REFERENCE_LIB_REG_EXP)) {
      libs.add(String(lib).toLowerCase());
    }
  }

  return [...libs].sort();
}

function collectAllTypes(): string[] {
  const { options } = parseTsConfig(RepoPaths.TsConfigJson);
  return (options.types ?? [])
    .filter((type) => DECLARATION_REFERENCE_TYPES.has(type))
    .sort();
}

function collectEnvironmentDirectives(params: CollectEnvironmentDirectivesParams): Map<string, string> {
  const { availableTypes, declarationFiles } = params;
  const { options } = parseTsConfig(RepoPaths.TsConfigJson);
  const program = createProgram({
    options: { ...options, noEmit: true },
    rootNames: declarationFiles.map((file) => resolveNative(RepoPaths.Src, file))
  });
  const checker = program.getTypeChecker();
  const directivesByFile = new Map<string, string>();

  for (const file of declarationFiles) {
    // The program was handed every one of these as a root name, so each one is in it.
    const sourceFile = ensureNonNullable(program.getSourceFile(resolveNative(RepoPaths.Src, file)));
    const libs = new Set<string>();
    const types = new Set<string>();

    function visit(node: Node): void {
      if (isIdentifier(node) || isStringLiteral(node)) {
        const $symbol = checker.getSymbolAtLocation(node);
        if ($symbol !== undefined) {
          addEnvironmentGlobals({ libs, program, symbol: resolveAlias(checker, $symbol), types });
        }
      }
      forEachChild(node, visit);
    }
    visit(sourceFile);

    const neededTypes = [...types].filter((type) => availableTypes.includes(type));
    if (libs.size > 0 || neededTypes.length > 0) {
      directivesByFile.set(
        file,
        (libs.size > 0 ? buildAllReferenceLibDirectives([...libs].sort()) : '') + buildAllReferenceTypesDirectives(neededTypes.sort())
      );
    }
  }

  return directivesByFile;
}

async function generateIndex(params: GenerateIndexParams): Promise<GenerateIndexResult> {
  const { folder } = params;
  const dirents = await readdirPosix(folder, { withFileTypes: true });
  const maybeLines = await asyncMap(dirents, (dirent) => handleIndexDirent(params, dirent));
  const lines = maybeLines.filter((line) => line !== undefined);

  if (lines.length === 0) {
    return GenerateIndexResult.Skipped;
  }

  await generate(join(folder, RepoPaths.IndexTs), lines);
  return GenerateIndexResult.Success;
}

async function getLibFiles(): Promise<string[]> {
  let files = await readdirPosix(RepoPaths.Src, { recursive: true });
  files = files.map((file) => normalizeIfRelative(join(RepoPaths.Src, file)));
  return files.filter((file) =>
    file.endsWith(RepoPaths.TsExtension) && !file.endsWith(RepoPaths.DtsExtension) && !file.endsWith('.test.ts')
    && !file.includes(`/${RepoPaths.TestHelpers}/`)
  );
}

async function handleIndexDirent(params: GenerateIndexParams, dirent: Dirent): Promise<string | undefined> {
  const { excludedPaths, folder, unmatchedPaths } = params;
  if (isExcludedFromIndex(folder, dirent)) {
    return;
  }

  const path = join(folder, dirent.name);
  if (excludedPaths.has(path)) {
    unmatchedPaths.delete(path);
    return;
  }

  let sourceFile: string;
  let name: string;
  if (dirent.isDirectory()) {
    const result = await generateIndex({ ...params, folder: path });
    if (result !== GenerateIndexResult.Success) {
      return;
    }
    sourceFile = normalizeIfRelative(join(dirent.name, RepoPaths.IndexTs));
    name = dirent.name;
  } else {
    const extension = extname(dirent.name);
    name = basename(dirent.name, extension);
    sourceFile = normalizeIfRelative(dirent.name);
  }

  return `export * as '${name}' from '${sourceFile}';`;
}

function isEnvironmentLib(lib: string): boolean {
  return ENVIRONMENT_LIB_PREFIXES.some((prefix) => lib.startsWith(prefix));
}

function isExcludedFileName(name: string): boolean {
  return !name.endsWith(RepoPaths.TsExtension) || name.endsWith('.test.ts') || name === 'setup.ts' || name.endsWith('-setup.ts');
}

function isExcludedFromIndex(folder: string, dirent: Dirent): boolean {
  const excludedNames: readonly string[] = [RepoPaths.IndexTs, RepoPaths.Types, RepoPaths.Styles, RepoPaths.TestHelpers];
  const isExcludedEntry = excludedNames.includes(dirent.name) || dirent.name.endsWith(RepoPaths.DtsExtension) || folder.split('/').includes(RepoPaths.Types);
  return isExcludedEntry || (dirent.isFile() && isExcludedFileName(dirent.name));
}

function resolveAlias(checker: TypeChecker, $symbol: TsSymbol): TsSymbol {
  // eslint-disable-next-line no-bitwise -- `SymbolFlags` is a bit set.
  return ($symbol.flags & SymbolFlags.Alias) === 0 ? $symbol : checker.getAliasedSymbol($symbol);
}

async function setExport(params: SetExportParams): Promise<void> {
  const { exportConditions, isWildcard, sourceCondition, srcFolder } = params;
  const importPath = replaceAll({
    $string: srcFolder,
    replacer: RepoPaths.CurrentFolder,
    searchValue: RepoPaths.Src
  });
  const conditionPath = isWildcard ? `${importPath}/${RepoPaths.Any}` : importPath;
  const dmtsPath = toDistPath({ format: RepoPaths.Esm, importPath, name: isWildcard ? RepoPaths.AnyDmts : RepoPaths.IndexDmts });
  const dctsPath = toDistPath({ format: RepoPaths.Cjs, importPath, name: isWildcard ? RepoPaths.AnyDcts : RepoPaths.IndexDcts });
  const dmtsFolderPath = dirname(dmtsPath);
  const dctsFolderPath = dirname(dctsPath);

  if (!isWildcard && !existsSync(dctsPath)) {
    return;
  }

  const isTypesOnly = importPath.includes(RepoPaths.Types);
  const mjsPath = toDistPath({ format: RepoPaths.Esm, importPath, name: isWildcard ? RepoPaths.AnyMjs : RepoPaths.IndexMjs });
  const cjsPath = toDistPath({ format: RepoPaths.Cjs, importPath, name: isWildcard ? RepoPaths.AnyCjs : RepoPaths.IndexCjs });

  if (isTypesOnly) {
    exportConditions[conditionPath] = {
      import: {
        types: dmtsPath
      },
      require: {
        types: dctsPath
      }
    };
  } else {
    const sourcePath = normalizeIfRelative(join(RepoPaths.Src, importPath, isWildcard ? RepoPaths.AnyTs : RepoPaths.IndexTs));

    exportConditions[conditionPath] = {
      /* eslint-disable perfectionist/sort-objects -- Order matters once it is written to `package.json`. */
      // First, so it wins wherever it is set: inside the repository, before anything is built.
      ...(sourceCondition !== undefined && { [sourceCondition]: sourcePath }),
      import: {
        types: dmtsPath,
        default: mjsPath
      },
      require: {
        types: dctsPath,
        default: cjsPath
      }
      /* eslint-enable perfectionist/sort-objects -- Order matters once it is written to `package.json`. */
    };
  }

  if (importPath === RepoPaths.CurrentFolder as string) {
    return;
  }

  if (!isWildcard) {
    await writeSubpathPackageJson(
      importPath,
      isTypesOnly
        ? { type: 'module', types: relative(importPath, dctsPath) }
        : { main: relative(importPath, cjsPath), module: relative(importPath, mjsPath), type: 'module', types: relative(importPath, dctsPath) }
    );
    return;
  }

  for (const file of await readdirPosix(dctsFolderPath)) {
    if (!file.endsWith(RepoPaths.DctsExtension)) {
      continue;
    }
    const name = basename(file, RepoPaths.DctsExtension);
    const packageJsonFolderPath = join(importPath, name);
    const types = relative(packageJsonFolderPath, join(dctsFolderPath, name + RepoPaths.DctsExtension));
    await writeSubpathPackageJson(
      packageJsonFolderPath,
      isTypesOnly
        ? { type: 'module', types }
        : {
          main: relative(packageJsonFolderPath, join(dctsFolderPath, name + RepoPaths.CjsExtension)),
          module: relative(packageJsonFolderPath, join(dmtsFolderPath, name + RepoPaths.MjsExtension)),
          type: 'module',
          types
        }
    );
  }
}

function toCtsContent(content: string): string {
  let ctsContent = replaceAll({
    $string: content,
    replacer: 'from \'$<ImportPath>.cjs\';',
    searchValue: STATIC_IMPORT_REG_EXP
  });
  ctsContent = replaceAll({
    $string: ctsContent,
    replacer: 'import($<Quote>$<ImportPath>.cjs$<Quote>)',
    searchValue: DYNAMIC_IMPORT_REG_EXP
  });

  // A `.d.cts` file is a CommonJS module. Type-only imports of a bare specifier resolving to an
  // ESM-only package need a `resolution-mode` attribute, else `tsc` reports TS1541 / TS1542.
  // Passing `'import'` is valid for CommonJS targets too, so every bare specifier receives it.
  // The ESM `.d.mts` needs no such attribute, so this transform runs on CommonJS content only.
  ctsContent = replaceAll({
    $string: ctsContent,
    replacer: 'import type $<Clause> from \'$<Specifier>\' with { \'resolution-mode\': \'import\' };',
    searchValue: BARE_TYPE_IMPORT_REG_EXP
  });
  return replaceAll({
    $string: ctsContent,
    replacer: 'import($<Quote>$<Specifier>$<Quote>, { with: { \'resolution-mode\': \'import\' } })',
    searchValue: BARE_INLINE_IMPORT_TYPE_REG_EXP
  });
}

function toDistPath(params: ToDistPathParams): string {
  return normalizeIfRelative(join(RepoPaths.DistLib, params.format, params.importPath, params.name));
}

function toLibName(libFilePath: string): string {
  // A lib a package replaced (`@typescript/lib-dom`, `@typescript/lib-dom/iterable.d.ts`) is named by its path, not by
  // its file name, which is `index.d.ts` for the lib's root.
  const replacementMatch = LIB_REPLACEMENT_REG_EXP.exec(libFilePath);
  if (replacementMatch?.groups !== undefined) {
    // The regular expression always captures both groups.
    const lib = String(replacementMatch.groups['Lib']);
    const subLib = String(replacementMatch.groups['SubLib']);
    return (subLib === 'index' ? lib : `${lib}.${subLib.replaceAll('/', '.')}`).toLowerCase();
  }
  return basename(libFilePath).toLowerCase().replace(/^lib\./, '').replace(/\.d\.ts$/, '');
}

function toMtsContent(content: string): string {
  const mtsContent = replaceAll({
    $string: content,
    replacer: 'from \'$<ImportPath>.mjs\';',
    searchValue: STATIC_IMPORT_REG_EXP
  });
  return replaceAll({
    $string: mtsContent,
    replacer: 'import($<Quote>$<ImportPath>.mjs$<Quote>)',
    searchValue: DYNAMIC_IMPORT_REG_EXP
  });
}

async function writeSubpathPackageJson(folder: string, packageJson: PackageJson): Promise<void> {
  await mkdir(folder, { recursive: true });
  await writeJson(join(folder, RepoPaths.PackageJson), packageJson);
}
