/**
 * Options for {@link buildLibrary}.
 */
export interface BuildLibraryOptions {
  /**
   * Creates the preprocess plugin for one output format. Defaults to the generic one, which carries no
   * environment-specific `require` patch.
   */
  readonly preprocessPluginFactory?: (isEsm: boolean) => Plugin;
}

/**
 * Options for {@link generateLibraryExports}.
 */
export interface GenerateLibraryExportsOptions {
  /**
   * Entries for files that are not built from a source folder (a folder of shared `tsconfig` presets, ambient `.d.ts`
   * files), keyed by subpath. They go into the map after the generated entries, as given, and count toward its change
   * check; no subpath stub is written for them. A key a source folder already generates throws.
   */
  readonly additionalExports?: Readonly<Record<string, PackageJson.Exports>> | undefined;

  /**
   * An export condition to put first in every entry, mapping the subpath onto its TypeScript source. Only a
   * repository holding several packages that import each other needs one; nothing outside it sets the condition, and
   * the sources it points at do not ship, so the publish has to strip it again. Omitted, the map has none.
   */
  readonly sourceCondition?: string | undefined;
}

/**
 * Options for {@link generateLibraryIndex}.
 */
export interface GenerateLibraryIndexOptions {
  /**
   * Source modules or folders to leave off the generated barrels, as paths from the package root
   * (`src/demo-vault-buttons.ts`, `src/test-runners/integration`). A module that needs an optional peer, or one that
   * runs code at load time which only works inside a test runner, goes here, so importing a barrel never loads it. It is
   * still built and stays reachable through its own subpath export. A path that names nothing the barrels would export
   * throws, so a rename cannot quietly put the module back.
   */
  readonly excludeFromIndex?: readonly string[] | undefined;
}

type ModuleFormat = 'cjs' | 'esm';

const DECLARATION_REFERENCE_TYPES = new Set(['node']);

// The libs that describe a host's globals rather than the language, which consumers conflict over. Each declaration
// gets the ones it uses; every other lib is shared through `library-references`.
const ENVIRONMENT_LIB_PREFIXES: readonly string[] = ['dom', 'scripthost', 'webworker'];
const NODE_TYPES_PATH_SEGMENT = '/node_modules/@types/node/';
const LIB_REPLACEMENT_REG_EXP = /\/node_modules\/@typescript\/lib-(?<Lib>[^/]+)\/(?<SubLib>.+)\.d\.ts$/;

// The declaration that carries only the `lib` and `types` references. Every declaration but the root one references
// it, rather than the root barrel, which would load every module of the package, optional peers' types included.
const LIBRARY_REFERENCES_FILE_NAME = 'library-references';
// Spelled apart on purpose: {@link collectAllLibs} scans every source file of the package being built for the
// directive, this one included, so a literal one here would be read as a lib this package needs.
const REFERENCE_LIB_DIRECTIVE = ['<reference', 'lib='].join(' ');
const REFERENCE_LIB_REG_EXP = /\/\/\/ <reference lib="(?<Lib>[^"]+)" \/>/gm;

// A bare-specifier (non-relative) type-only import, e.g. `import type { Promisable } from 'type-fest';`.
const BARE_TYPE_IMPORT_REG_EXP = /^import type (?<Clause>.+?) from '(?<Specifier>[^.'][^']*)';$/gm;

// A bare-specifier (non-relative) inline import type node, e.g. `import("type-fest").Promisable`. Either quote: the
// emit writes double quotes, while a hand-written declaration copied as is keeps the single quotes dprint writes.
const BARE_INLINE_IMPORT_TYPE_REG_EXP = /import\((?<Quote>["'])(?<Specifier>[^."'][^"']*)\k<Quote>\)/g;

const STATIC_IMPORT_REG_EXP = /from '(?<ImportPath>.+?)\.ts';/gm;

// Inline import-type nodes (`typeof import('./foo.ts')`) preserve the source quote style.
// Hand-authored `.d.ts` files emit single quotes; tsc-generated declarations emit double quotes.
// Capture the quote and reuse it in the replacement so both styles are rewritten.
const DYNAMIC_IMPORT_REG_EXP = /import\((?<Quote>['"])(?<ImportPath>.+?)\.ts\k<Quote>\)/gm;

